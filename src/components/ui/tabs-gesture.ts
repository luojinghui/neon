export type TabDragDirection = 'pending' | 'horizontal' | 'vertical';

export function tabDragDirection(dx: number, dy: number, threshold = 6): TabDragDirection {
  if (Math.abs(dy) > threshold && Math.abs(dy) > Math.abs(dx)) return 'vertical';
  return Math.abs(dx) < threshold ? 'pending' : 'horizontal';
}

export function nearestTab<T extends { left: number; width: number; disabled?: boolean }>(items: T[], pointerX: number): T | undefined {
  return items.filter(item => !item.disabled).reduce<T | undefined>((best, item) => !best
    || Math.abs(item.left + item.width / 2 - pointerX) < Math.abs(best.left + best.width / 2 - pointerX) ? item : best, undefined);
}

/** Physical scroll delta also works with browsers' negative scrollLeft in RTL. */
export function tabDragScrollStep(pointerX: number, viewportLeft: number, viewportWidth: number): number {
  const edge = Math.min(24, viewportWidth / 4);
  if (edge <= 0) return 0;
  const start = viewportLeft + edge, end = viewportLeft + viewportWidth - edge;
  if (pointerX < start) return -Math.ceil(Math.min(1, (start - pointerX) / edge) * 8);
  if (pointerX > end) return Math.ceil(Math.min(1, (pointerX - end) / edge) * 8);
  return 0;
}

/** Suppress only the click generated by a drag. A fresh pointerdown always starts a real new action. */
export function createTabClickGuard() {
  let pending = false;
  return {
    afterDrag() { pending = true; },
    pointerDown() { pending = false; },
    suppress(detail: number) {
      if (detail <= 0 || !pending) return false;
      pending = false;
      return true;
    }
  };
}
