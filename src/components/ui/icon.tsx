export type IconName = keyof typeof iconRegistry;
export const iconNames = Object.keys(iconRegistry) as IconName[];
export type IconSize = 'sm' | 'md' | 'lg' | number;
export interface IconProps extends Omit<HTMLAttributes<HTMLSpanElement>, 'children'> {
  name: IconName;
  size?: IconSize;
  /** Hearts become filled red; the brief feedback respects reduced motion. */
  active?: boolean;
  spin?: boolean;
  tone?: 'inherit' | 'primary' | 'danger' | 'success';
  /** Decorative by default. Supply a label only for a standalone meaningful icon. */
  label?: string;
}

export const Icon = forwardRef<HTMLSpanElement, IconProps>(function Icon({
  name, size = 'md', active = false, spin, tone = 'inherit', label, className, style, ...props
}, ref) {
  const Glyph = name === 'heart' && active ? HeartFilled : iconRegistry[name];
  return <span {...props} ref={ref} className={[styles.icon, className].filter(Boolean).join(' ')}
    data-ui-icon={name} data-size={typeof size === 'number' ? undefined : size}
    data-active={active || undefined} data-spin={(spin ?? name === 'loading') || undefined} data-tone={tone}
    role={label ? 'img' : undefined} aria-label={label} aria-hidden={label ? undefined : true}
    style={{ ...(typeof size === 'number' ? { '--icon-size': `${size}px` } : {}), ...style } as CSSProperties}>
    <Glyph aria-hidden="true" spin={false} />
  </span>;
});
