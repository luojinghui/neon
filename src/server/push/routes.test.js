const test = require('node:test');
const assert = require('node:assert/strict');
const express = require('express');
const fs = require('node:fs/promises');
const os = require('node:os');
const path = require('node:path');
const { createECDH, randomBytes } = require('node:crypto');
const webpush = require('web-push');
const { PushRepository } = require('./repository');
const { createPushRouter, createAdminPushRouter } = require('./routes');

test('HTTP subscription identity/origin checks and private admin send workflow', async t => {
  const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'neon-push-http-'));
  const uuid = 'd9428888-122b-4a8b-8a4b-0d2b0f4f3552';
  const profile = { uuid, name: 'Tester', userId: 'Tester' };
  const profiles = { getByUuid: value => value === uuid ? profile : null, listProfiles: () => [profile] };
  const sent = [];
  const audited = [];
  const repository = new PushRepository({ dataFile: path.join(directory, 'push.json'), env: {}, transport: { generateVAPIDKeys: webpush.generateVAPIDKeys, sendNotification: async (...args) => { sent.push(args); } } });
  const app = express();
  app.use('/api/push', createPushRouter({ repository, profiles }));
  app.use('/admin/push', (req, res, next) => {
    if (req.get('authorization') !== 'test-admin') return res.status(401).end();
    req.admin = { username: 'tester' }; next();
  }, express.json(), createAdminPushRouter({ repository, profiles, audit: async (...args) => { audited.push(args); } }));
  const server = app.listen(0, '127.0.0.1');
  await new Promise(resolve => server.once('listening', resolve));
  t.after(async () => { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await fs.rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const configResponse = await fetch(`${base}/api/push/config`);
  assert.equal(configResponse.headers.get('cache-control'), 'no-store');
  const config = await configResponse.json();
  assert.deepEqual(Object.keys(config), ['publicKey']);
  const key = createECDH('prime256v1'); key.generateKeys();
  const subscription = { endpoint: 'https://fcm.googleapis.com/send/fixture', keys: { p256dh: key.getPublicKey().toString('base64url'), auth: randomBytes(16).toString('base64url') } };
  const headers = { 'content-type': 'application/json', 'x-neon-user-uuid': uuid, 'user-agent': 'HTTP fixture UA' };
  const body = JSON.stringify({ subscription });
  assert.equal((await fetch(`${base}/api/push/subscriptions`, { method: 'POST', body, headers: { 'content-type': 'application/json' } })).status, 401);
  assert.equal((await fetch(`${base}/api/push/subscriptions`, { method: 'POST', body, headers: { ...headers, origin: 'https://attacker.invalid' } })).status, 403);
  assert.equal((await fetch(`${base}/api/push/subscriptions`, { method: 'POST', body, headers })).status, 201);
  assert.equal((await fetch(`${base}/admin/push`)).status, 401);
  const dashboard = await (await fetch(`${base}/admin/push`, { headers: { authorization: 'test-admin' } })).json();
  assert.equal(dashboard.recipients[0].devices[0].userAgent, 'HTTP fixture UA');
  assert.equal(JSON.stringify(dashboard).includes(subscription.keys.auth), false);
  const result = await fetch(`${base}/admin/push/messages`, { method: 'POST', headers: { 'content-type': 'application/json', authorization: 'test-admin' }, body: JSON.stringify({ title: '测试标题', body: '测试内容', url: '/moments', audience: 'users', uuids: [uuid] }) });
  assert.equal(result.status, 201);
  assert.equal((await result.json()).item.accepted, 1);
  assert.equal(sent.length, 1);
  assert.equal(audited[0][1], 'push.send');
  assert.equal((await fetch(`${base}/api/push/subscriptions`, { method: 'DELETE', headers, body: JSON.stringify({ endpoint: subscription.endpoint }) })).status, 204);
  assert.equal((await repository.read()).subscriptions.length, 0);
});
